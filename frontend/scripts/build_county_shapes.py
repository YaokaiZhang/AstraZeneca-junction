#!/usr/bin/env python3
"""Build src/data/countyShapes.generated.ts: wellbeing services county outlines as SVG paths.

Source: Statistics Finland, statistical areas (tilastointialueet), layer hyvinvointialue4500k, 2026, CC BY 4.0.
Projected exactly like src/data/finland.ts so the shapes sit on the same 514.9 × 1000 canvas.

Run from frontend/:  python3 scripts/build_county_shapes.py
"""
import json, math, urllib.request

URL = ('https://geo.stat.fi/geoserver/tilastointialueet/wfs?service=WFS&version=2.0.0&request=GetFeature'
       '&typeName=tilastointialueet:hyvinvointialue4500k&outputFormat=json&srsName=EPSG:4326')
K = math.cos(math.radians(64.5))
S = 95.38673555371851
TOL = 0.9        # simplification tolerance, canvas units (canvas is 1000 tall)
MIN_AREA = 6     # drop islets smaller than this, canvas units²

# Statistics Finland code → our county id. 91 (Åland) is not a wellbeing services county and is left out.
IDS = {
  '01': 'ita-uusimaa', '02': 'keski-uusimaa', '03': 'lansi-uusimaa', '04': 'vantaa-kerava', '05': 'varsinais-suomi',
  '06': 'satakunta', '07': 'kanta-hame', '08': 'pirkanmaa', '09': 'paijat-hame', '10': 'kymenlaakso',
  '11': 'etela-karjala', '12': 'etela-savo', '13': 'pohjois-savo', '14': 'pohjois-karjala', '15': 'keski-suomi',
  '16': 'etela-pohjanmaa', '17': 'pohjanmaa', '18': 'keski-pohjanmaa', '19': 'pohjois-pohjanmaa', '20': 'kainuu',
  '21': 'lappi', '90': 'helsinki',
}


def project(lon, lat):
  return ((lon - 19) * K * S, (70.3 - lat) * S)


def dp(pts, tol):
  """Douglas–Peucker on an open polyline."""
  if len(pts) < 3:
    return pts
  (x1, y1), (x2, y2) = pts[0], pts[-1]
  dx, dy = x2 - x1, y2 - y1
  n = math.hypot(dx, dy) or 1e-9
  best, bi = 0, 0
  for i in range(1, len(pts) - 1):
    x, y = pts[i]
    d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / n
    if d > best:
      best, bi = d, i
  if best <= tol:
    return [pts[0], pts[-1]]
  return dp(pts[:bi + 1], tol)[:-1] + dp(pts[bi:], tol)


def area(r):
  return 0.5 * sum(r[i][0] * r[i - 1][1] - r[i - 1][0] * r[i][1] for i in range(len(r)))


def centroid(r):
  a = area(r) or 1e-9
  cx = sum((r[i][0] + r[i - 1][0]) * (r[i][0] * r[i - 1][1] - r[i - 1][0] * r[i][1]) for i in range(len(r))) / (6 * a)
  cy = sum((r[i][1] + r[i - 1][1]) * (r[i][0] * r[i - 1][1] - r[i - 1][0] * r[i][1]) for i in range(len(r))) / (6 * a)
  return cx, cy


def main():
  data = json.load(urllib.request.urlopen(URL, timeout=60))
  out = {}
  for f in data['features']:
    cid = IDS.get(f['properties']['hyvinvointialue'])
    if not cid:
      continue
    rings = []
    g = f['geometry']
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    for poly in polys:
      for ring in poly[:1]:  # outer rings only; the layer has no lakes cut out
        pts = [project(lon, lat) for lon, lat in ring]
        # split the closed ring in two so DP keeps a stable shape
        h = len(pts) // 2
        s = dp(pts[:h + 1], TOL)[:-1] + dp(pts[h:], TOL)
        if len(s) >= 4 and abs(area(s)) >= MIN_AREA:
          rings.append(s)
    big = max(rings, key=lambda r: abs(area(r)))
    cx, cy = centroid(big)
    d = ''.join('M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in r[:-1]) + 'Z' for r in rings)
    out[cid] = {'d': d, 'cx': round(cx, 1), 'cy': round(cy, 1)}
  assert len(out) == 22, sorted(out)
  with open('src/data/countyShapes.generated.ts', 'w') as fh:
    fh.write('// GENERATED by scripts/build_county_shapes.py from Statistics Finland statistical areas\n')
    fh.write('// (hyvinvointialue4500k, 2026, CC BY 4.0). Same projection as finland.ts. Do not edit.\n')
    fh.write('export const COUNTY_SHAPES: Record<string, { d: string; cx: number; cy: number }> = ')
    fh.write(json.dumps(out, separators=(',', ':')).replace('},"', '},\n  "'))
    fh.write('\n')
  print('wrote', sum(len(v['d']) for v in out.values()), 'chars')


if __name__ == '__main__':
  main()
